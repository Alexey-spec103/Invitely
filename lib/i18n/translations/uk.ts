/** Ukrainian noun plurals depend on the count itself (1 гість, 2-4 гості,
 * 0/5+/11-14 гостей) -- same reasoning as pl.ts/ru.ts's equivalents. */
function guestWordUk(count: number): string {
  const lastDigit = count % 10;
  const lastTwo = count % 100;
  if (lastDigit === 1 && lastTwo !== 11) return "гість";
  if (lastDigit >= 2 && lastDigit <= 4 && !(lastTwo >= 12 && lastTwo <= 14)) return "гості";
  return "гостей";
}

/** Same reasoning as guestWordUk above, for "відповідь" (response) -- used
 * by the email dictionary's RSVP-count copy (1 відповідь, 2-4 відповіді,
 * 5+ відповідей). */
function responseWordUk(count: number): string {
  const lastDigit = count % 10;
  const lastTwo = count % 100;
  if (lastDigit === 1 && lastTwo !== 11) return "відповідь";
  if (lastDigit >= 2 && lastDigit <= 4 && !(lastTwo >= 12 && lastTwo <= 14)) return "відповіді";
  return "відповідей";
}

